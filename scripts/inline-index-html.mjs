/**
 * Inlines the BUILT dist/index.html into the renderSeoContent Cloud Function.
 *
 * Firebase Hosting rewrites /learning/** to that function, so every human
 * pageview of a course page is a function invocation. The function used to
 * fetch https://careervivid.app/index.html over the public internet on each
 * cold instance just to serve it straight back — a network round-trip to our
 * own CDN, on the critical path, inside a 30s budget. When that fetch was slow
 * the container died and Google served its own "Error: Server Error" page.
 *
 * Baking the HTML into the deployed bundle removes the hop entirely: a cold
 * instance answers from a string constant.
 *
 * It must be the BUILT index.html, not the source one — the source references
 * /src/entry-client.tsx, which does not exist in production. Vite injects the
 * hashed asset URLs during build, which is why this runs after build:vite.
 *
 * Run from scripts/build.mjs after the Vite build. If dist/index.html is
 * missing this writes an empty constant rather than failing, and the function
 * falls back to its (timeout-guarded) network fetch — so `firebase deploy
 * --only functions` on its own still produces a working deploy.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'dist', 'index.html');
const OUT = path.join(ROOT, 'functions', 'src', 'seo', 'indexHtml.generated.ts');

let html = '';
if (fs.existsSync(SRC)) {
    html = fs.readFileSync(SRC, 'utf-8');
} else {
    console.warn(`[inline-index-html] ${path.relative(ROOT, SRC)} not found — writing an empty constant.`);
    console.warn('[inline-index-html] renderSeoContent will fall back to fetching index.html at runtime.');
}

fs.writeFileSync(OUT, [
    '// AUTO-GENERATED by scripts/inline-index-html.mjs — do not edit by hand.',
    '//',
    '// The built dist/index.html, baked in at deploy time so renderSeoContent can',
    '// serve human traffic without a runtime network fetch. Regenerated on every',
    '// `npm run build`. Empty means the web app had not been built yet; the',
    '// function falls back to fetching index.html over the network.',
    '',
    `export const INDEX_HTML: string = ${JSON.stringify(html)};`,
    '',
].join('\n'));

console.log(
    html
        ? `[inline-index-html] inlined ${html.length} bytes into functions/src/seo/indexHtml.generated.ts`
        : '[inline-index-html] wrote empty constant (no dist/index.html)',
);
