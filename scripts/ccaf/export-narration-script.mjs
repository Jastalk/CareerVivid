/**
 * Exports the narration script as a readable markdown document.
 *
 * Run automatically at the end of every film build, so the document cannot
 * drift from what the film actually says. It drifted once already: the beats
 * were rewritten into third person while the exported script still showed the
 * old second-person lines, and nothing flagged it.
 *
 * The timings are measured from the real WAV byte counts, not estimated, so
 * this doubles as a timing sheet that matches the finished cut.
 *
 *   npx tsx scripts/ccaf/export-narration-script.mjs
 */

import fs from 'fs';
import path from 'path';
import { DOMAIN_1_FILM } from './domain1Script.ts';

const NARRATION_DIR = path.resolve('public/assets/ccaf-narration/domain-1-overview/en/chirp-fenrir');
const OUT = path.resolve('scripts/ccaf/domain-1-narration-script.md');

const CHAPTER = {
    'open-buried': 'Prologue', 'roadmap': 'Overview',
    'what-is-a-turn': 'Chapter 0 · Before Any Jargon', 'term-what-comes-back': 'Chapter 0 · Before Any Jargon',
    'why-a-loop-exists': 'Chapter 0 · Before Any Jargon', 'term-why-a-loop': 'Chapter 0 · Before Any Jargon',
    'two-different-limits': 'Chapter 0 · Before Any Jargon', 'term-two-limits': 'Chapter 0 · Before Any Jargon',
    'term-whose-field': 'Chapter 0 · Before Any Jargon',
    'no-brakes': 'Chapter 1 · One Agent, One Loop', 'listen-not-count': 'Chapter 1 · One Agent, One Loop',
    'stop-reason': 'Chapter 1 · One Agent, One Loop', 'three-blank-letters': 'Chapter 1 · One Agent, One Loop',
    'three-coats': 'Chapter 1 · One Agent, One Loop',
    'queue-of-helpers': 'Chapter 2 · Splitting the Work', 'note-in-your-hand': 'Chapter 2 · Splitting the Work',
    'dont-delegate': 'Chapter 2 · Splitting the Work', 'proofreading-pass': 'Chapter 2 · Splitting the Work',
    'three-passes': 'Chapter 2 · Splitting the Work', 'script-vs-goal': 'Chapter 2 · Splitting the Work',
    'directions-vs-destination': 'Chapter 2 · Splitting the Work', 'brief-with-goals': 'Chapter 2 · Splitting the Work',
    'dominoes': 'Chapter 3 · Order and Speed', 'ice-before-baking': 'Chapter 3 · Order and Speed',
    'forced-first': 'Chapter 3 · Order and Speed', 'twelve-washing-machines': 'Chapter 3 · Order and Speed',
    'twelve-at-once': 'Chapter 3 · Order and Speed',
    'canyon-shout': 'Chapter 4 · What Falls in the Gap', 'shift-handover': 'Chapter 4 · What Falls in the Gap',
    'no-inheritance': 'Chapter 4 · What Falls in the Gap', 'two-witnesses': 'Chapter 4 · What Falls in the Gap',
    'two-numbers': 'Chapter 4 · What Falls in the Gap', 'evidence-bag': 'Chapter 4 · What Falls in the Gap',
    'citation-id': 'Chapter 4 · What Falls in the Gap',
    'burst-pipes': 'Chapter 5 · When It Breaks', 'back-from-holiday': 'Chapter 5 · When It Breaks',
    'tell-it-what-changed': 'Chapter 5 · When It Breaks', 'corrupted-autosave': 'Chapter 5 · When It Breaks',
    'checkpoint': 'Chapter 5 · When It Breaks', 'three-burnt-dishes': 'Chapter 5 · When It Breaks',
    'three-hundred': 'Chapter 5 · When It Breaks',
    'thirteen-doors': 'Epilogue', 'go-find-out': 'Epilogue',
};

const wavSeconds = (p) => fs.existsSync(p) ? (fs.statSync(p).size - 44) / (24000 * 2) : 0;
const mmss = (t) => `${String(Math.floor(t / 60)).padStart(2, '0')}:${String(Math.floor(t % 60)).padStart(2, '0')}`;

const lines = [
    '# Domain 1 · TTS Narration Script',
    '',
    '> **Review copy — regenerated by every film build.** Read it, mark up what should',
    '> change, and the edits go into `scripts/ccaf/domain1Script.ts`; this file is',
    '> rewritten from there and will lose anything typed directly into it.',
    '>',
    '> (`import-narration-script.mjs` can push edits from here back into the script if',
    '> that is ever wanted, but it is deliberately not part of the build.)',
    '',
    'Voice: **en-US-Chirp3-HD-Fenrir** · 24 kHz LINEAR16 mono.',
    'TTS speaks the **English only** — the Chinese line is subtitle text and is never synthesized.',
    '',
    'Narrated in the third person: the lesson follows **Leo** building an agency, rather than',
    'telling the viewer what to do. An earlier cut said "you" 96 times, which read as instruction',
    'rather than storytelling. The one surviving "you" is the last line, on purpose.',
    '',
];

let t = 0;
let chapter = '';
let words = 0;
for (const beat of DOMAIN_1_FILM.beats) {
    const wav = path.join(NARRATION_DIR, `${beat.id}.wav`);
    const spoken = wavSeconds(wav);
    const duration = spoken ? spoken + 0.35 : 3.2;
    const ch = CHAPTER[beat.id] ?? 'Unassigned';
    if (ch !== chapter) { chapter = ch; lines.push('', `## ${ch}`, ''); }

    const tag = beat.clip ? '  ·  _Remotion 机制动画_' : '';
    lines.push(`### \`${beat.id}\`  ·  ${mmss(t)} → ${mmss(t + duration)}  (${duration.toFixed(1)}s)${tag}`, '');
    lines.push(`> ${beat.narration?.en ?? '_(no narration)_'}`, '');
    if (beat.narration?.zh) lines.push(`中文字幕：${beat.narration.zh}`, '');
    words += beat.narration?.en.split(/\s+/).length ?? 0;
    t += duration;
}

lines.push('---', '', `**${DOMAIN_1_FILM.beats.length} 拍 · ${mmss(t)} · ${words} 词**`, '');
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`📄 narration script → ${OUT}  (${DOMAIN_1_FILM.beats.length} beats, ${mmss(t)})`);
